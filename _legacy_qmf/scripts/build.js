/**
 * Copy static assets
 */
function copyAssets() {
    const assetsDir = path.join(ROOT_DIR, 'assets');
    const distAssetsDir = path.join(DIST_DIR, 'assets');
    
    // Copy logo
    const logoSrc = path.join(assetsDir, 'logo');
    const logoDest = path.join(distAssetsDir, 'logo');
    if (fs.existsSync(logoSrc)) {
        fs.mkdirSync(logoDest, { recursive: true });
        fs.cpSync(logoSrc, logoDest, { recursive: true });
        console.log('✓ Copied logo assets');
    }
    
    // Copy icon-loader (needed at runtime)
    const iconLoaderSrc = path.join(assetsDir, 'icons/icon-loader.js');
    const iconLoaderDest = path.join(distAssetsDir, 'icons/icon-loader.js');
    if (fs.existsSync(iconLoaderSrc)) {
        fs.mkdirSync(path.dirname(iconLoaderDest), { recursive: true });
        fs.copyFileSync(iconLoaderSrc, iconLoaderDest);
        console.log('✓ Copied icon-loader');
    }
}

/**
 * Generate manifest.json and shim files
 */
function generateManifest(jsManifest, cssManifest) {
    const jsHashedFile = jsManifest['qmf.js'];
    const cssHashedFile = cssManifest['qmf.css'];
    
    // Read file contents for SRI
    const jsContent = fs.readFileSync(path.join(DIST_DIR, jsHashedFile), 'utf-8');
    const cssContent = fs.readFileSync(path.join(DIST_DIR, cssHashedFile), 'utf-8');
    
    const jsSRI = generateSRI(jsContent);
    const cssSRI = generateSRI(cssContent);
    
    const manifest = {
        version: '2.0.0',
        buildTime: new Date().toISOString(),
        mode: config.isProduction ? 'production' : 'development',
        base: config.isProduction ? config.cdnBase : '',
        files: {
            js: jsHashedFile,
            css: cssHashedFile
        },
        integrity: {
            js: jsSRI,
            css: cssSRI
        }
    };
    
    // Write manifest
    const manifestPath = path.join(DIST_DIR, 'manifest.json');
    fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
    console.log('✓ Generated manifest.json');
    
    // Generate stable shim files (qmf.js and qmf.css)
    generateShimFiles(jsHashedFile, cssHashedFile);
    
    // Generate HTML loader snippet
    generateHTMLLoader(manifest);
    
    return manifest;
}

/**
 * Generate stable shim files that re-export from hashed bundles
 */
function generateShimFiles(jsHashedFile, cssHashedFile) {
    // JS shim: re-export everything from hashed bundle
    const jsShim = `// QMF Stable Entry - v2.0.0
// This file re-exports from the hashed bundle
// DO NOT CACHE THIS FILE - use short TTL
export * from './${jsHashedFile}';
`;
    fs.writeFileSync(path.join(DIST_DIR, 'qmf.js'), jsShim);
    console.log('✓ Generated qmf.js (stable shim)');
    
    // CSS shim: import from hashed CSS
    const cssShim = `/* QMF Stable Entry - v2.0.0 */
/* This file imports from the hashed bundle */
/* DO NOT CACHE THIS FILE - use short TTL */
@import url('./${cssHashedFile}');
`;
    fs.writeFileSync(path.join(DIST_DIR, 'qmf.css'), cssShim);
    console.log('✓ Generated qmf.css (stable shim)');
}

/**
 * Generate HTML loader snippet
 */
function generateHTMLLoader(manifest) {
    const base = manifest.base || '';
    const jsFile = manifest.files.js;
    const cssFile = manifest.files.css;
    const jsSRI = manifest.integrity.js;
    const cssSRI = manifest.integrity.css;
    
    const html = `
<!-- QMF Loader - Auto-generated -->
<!-- Version: ${manifest.version} | Built: ${manifest.buildTime} -->

<!-- Option 1: Stable entries (auto-update, short cache) -->
<link rel="stylesheet" href="${base}/qmf/dist/qmf.css" crossorigin="anonymous">
<script type="module" src="${base}/qmf/dist/qmf.js"></script>

<!-- Option 2: Immutable with SRI (recommended for production) -->
<link rel="stylesheet" 
      href="${base}/qmf/dist/${cssFile}" 
      integrity="${cssSRI}"
      crossorigin="anonymous">
<script type="module"
        src="${base}/qmf/dist/${jsFile}"
        integrity="${jsSRI}"
        crossorigin="anonymous"></script>

<!-- Option 3: Version pinned -->
<link rel="stylesheet" href="${base}/qmf/v${manifest.version}/dist/qmf.css">
<script type="module" src="${base}/qmf/v${manifest.version}/dist/qmf.js"></script>

<!-- Usage Example -->
<script type="module">
import { 
    initQMF,
    eventBus,
    stateManager,
    authService,
    chatService,
    notificationService,
    initUI,
    getUIPlugin
} from '${base}/qmf/dist/qmf.js';

await initQMF({
    appId: 'YOUR_APP_ID',
    appName: 'Your App Name',
    endpoints: {
        auth: 'https://id.quizzman.com',
        chat: 'https://chat.quizzman.com',
        chatSocket: 'wss://chat.quizzman.com',
        notification: 'https://noti.quizzman.com',
        notiSocket: 'wss://noti.quizzman.com'
    },
    features: {
        chat: true,
        notifications: true
    }
});

await initUI({
    header: { container: '#qmf-header' },
    panels: '#qmf-panels',
    toasts: '#qmf-toasts'
});
</script>
`;
    
    fs.writeFileSync(path.join(DIST_DIR, 'loader.html'), html.trim());
    console.log('✓ Generated loader.html snippet');
}

/**
 * Watch mode
 */
async function watch() {
    console.log('👀 Watching for changes...\n');
    
    const ctx = await esbuild.context({
        entryPoints: Object.values(config.entries).map(e => path.resolve(ROOT_DIR, e)),
        bundle: true,
        outdir: DIST_DIR,
        format: 'esm',
        sourcemap: true
    });
    
    await ctx.watch();
}

/**
 * Main build function
 */
async function build() {
    console.log(`\n🔨 Building QMF ${config.isProduction ? '(production)' : '(development)'}...\n`);
    
    try {
        // Clean
        cleanDist();
        
        // Build JS
        const jsManifest = await buildJS();
        
        // Build CSS
        const cssManifest = await buildCSS();
        
        // Copy assets
        copyAssets();
        
        // Generate manifest
        generateManifest(jsManifest, cssManifest);
        
        console.log('\n✅ Build completed!\n');
        
        // Watch mode
        if (config.isWatch) {
            await watch();
        }
        
    } catch (error) {
        console.error('❌ Build failed:', error);
        process.exit(1);
    }
}

// Run
build();
