#!/usr/bin/env node
/**
 * QMF Build Script
 * Bundles all modules into production-ready assets with hashed filenames
 * Generates manifest.json for cache-busting
 * @version 2.0.0
 */

import * as esbuild from 'esbuild';
import * as fs from 'fs';
import * as path from 'path';
import * as crypto from 'crypto';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..');
const DIST_DIR = path.join(ROOT_DIR, 'dist');

/**
 * Build configuration
 */
const config = {
    isProduction: process.env.NODE_ENV === 'production',
    isWatch: process.argv.includes('--watch'),
    
    // Entry points for bundling
    entries: {
        // Main QMF bundle (includes everything)
        'qmf': './kernel/index.js'
    },
    
    // CSS entries
    cssEntries: [
        './plugins/header/header.css',
        './plugins/chat/chat-panel.css',
        './plugins/notification/notification-panel.css'
    ],
    
    // Output settings
    outdir: DIST_DIR,
    
    // CDN base for production
    cdnBase: 'https://ui.quizzman.com'
};

/**
 * Generate content hash
 */
function generateHash(content) {
    return crypto.createHash('md5').update(content).digest('hex').slice(0, 8);
}

/**
 * Generate SRI hash (sha384)
 */
function generateSRI(content) {
    const hash = crypto.createHash('sha384').update(content).digest('base64');
    return `sha384-${hash}`;
}

/**
 * Clean dist directory
 */
function cleanDist() {
    if (fs.existsSync(DIST_DIR)) {
        fs.rmSync(DIST_DIR, { recursive: true });
    }
    fs.mkdirSync(DIST_DIR, { recursive: true });
}

/**
 * Build JavaScript bundles
 */
async function buildJS() {
    const manifest = {};
    
    for (const [name, entry] of Object.entries(config.entries)) {
        const entryPath = path.resolve(ROOT_DIR, entry);
        
        // Build bundle
        const result = await esbuild.build({
            entryPoints: [entryPath],
            bundle: true,
            minify: config.isProduction,
            sourcemap: !config.isProduction,
            format: 'esm',
            target: ['es2020'],
            outdir: DIST_DIR,
            entryNames: config.isProduction ? `${name}.[hash]` : name,
            metafile: true,
            define: {
                'process.env.NODE_ENV': JSON.stringify(config.isProduction ? 'production' : 'development'),
                '__QMF_VERSION__': JSON.stringify('2.0.0'),
                '__QMF_CDN_BASE__': JSON.stringify(config.cdnBase)
            },
            external: config.isProduction ? [] : ['socket.io-client'],
            loader: {
                '.svg': 'text'
            }
        });
        
        // Extract output filename from metafile
        const outputs = Object.keys(result.metafile.outputs);
        const jsOutput = outputs.find(f => f.endsWith('.js'));
        
        if (jsOutput) {
            const outputName = path.basename(jsOutput);
            manifest[`${name}.js`] = outputName;
            
            console.log(`✓ Built ${name}.js → ${outputName}`);
        }
    }
    
    return manifest;
}

/**
 * Build CSS bundles
 */
async function buildCSS() {
    const manifest = {};
    
    // Combine all CSS files
    let combinedCSS = '';
    
    for (const cssPath of config.cssEntries) {
        const fullPath = path.resolve(ROOT_DIR, cssPath);
        if (fs.existsSync(fullPath)) {
            const content = fs.readFileSync(fullPath, 'utf-8');
            combinedCSS += `/* ${path.basename(cssPath)} */\n${content}\n\n`;
        }
    }
    
    // Add CSS custom properties/theme
    const themeCSS = generateThemeCSS();
    combinedCSS = themeCSS + combinedCSS;
    
    // Minify if production
    if (config.isProduction) {
        const result = await esbuild.transform(combinedCSS, {
            loader: 'css',
            minify: true
        });
        combinedCSS = result.code;
    }
    
    // Generate hash and write
    const hash = generateHash(combinedCSS);
    const filename = config.isProduction ? `qmf.${hash}.css` : 'qmf.css';
    
    fs.writeFileSync(path.join(DIST_DIR, filename), combinedCSS);
    manifest['qmf.css'] = filename;
    
    console.log(`✓ Built qmf.css → ${filename}`);
    
    return manifest;
}

