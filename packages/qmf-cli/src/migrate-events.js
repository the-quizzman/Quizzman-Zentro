/**
 * Migrate magic-string eventBus.emit/on → typed event stubs.
 */
import {
  readFileSync,
  writeFileSync,
  existsSync,
  readdirSync,
  statSync,
  mkdirSync,
} from 'node:fs';
import { join } from 'node:path';

const EMIT_RE = /(?:eventBus|QMF\.eventBus|\.events)\s*\.\s*emit\s*\(\s*['"`]([^'"`]+)['"`]/g;
const ON_RE = /(?:eventBus|QMF\.eventBus|\.events)\s*\.\s*on\s*\(\s*['"`]([^'"`]+)['"`]/g;

/**
 * @param {string} appRoot
 * @param {{ write?: boolean, outDir?: string }} [opts]
 */
export function migrateEvents(appRoot, opts = {}) {
  const srcRoot = join(appRoot, 'src');
  if (!existsSync(srcRoot)) throw new Error('No src/ directory');

  /** @type {Map<string, { files: Set<string>, emits: number, ons: number }>} */
  const events = new Map();

  /**
   * @param {string} dir
   */
  function walk(dir) {
    for (const name of readdirSync(dir)) {
      const p = join(dir, name);
      const st = statSync(p);
      if (st.isDirectory()) {
        if (name === 'node_modules' || name === 'dist') continue;
        walk(p);
        continue;
      }
      if (!/\.(js|mjs|cjs|ts)$/.test(name)) continue;
      const text = readFileSync(p, 'utf8');
      let m;
      const emitRe = new RegExp(EMIT_RE.source, 'g');
      while ((m = emitRe.exec(text))) {
        const ev = normalizeEventName(m[1]);
        const rec = events.get(ev) ?? { files: new Set(), emits: 0, ons: 0 };
        rec.files.add(p);
        rec.emits++;
        events.set(ev, rec);
      }
      const onRe = new RegExp(ON_RE.source, 'g');
      while ((m = onRe.exec(text))) {
        const ev = normalizeEventName(m[1]);
        const rec = events.get(ev) ?? { files: new Set(), emits: 0, ons: 0 };
        rec.files.add(p);
        rec.ons++;
        events.set(ev, rec);
      }
    }
  }

  walk(srcRoot);

  const outDir = opts.outDir ?? join(appRoot, 'src/runtime/events');
  /** @type {Array<{ name: string, ns: string, exportName: string, files: string[], emits: number, ons: number }>} */
  const stubs = [];

  for (const [name, rec] of [...events.entries()].sort()) {
    const ns = name.split('.')[0];
    const exportName = toExportName(name);
    stubs.push({
      name,
      ns,
      exportName,
      emits: rec.emits,
      ons: rec.ons,
      files: [...rec.files],
    });
  }

  let written = null;
  if (opts.write && stubs.length) {
    mkdirSync(outDir, { recursive: true });
    const body = [
      `/**`,
      ` * AUTO-GENERATED by qmf4 migrate events`,
      ` * Review payloads, then wire emit(Event, payload) / subscribe(Event, fn).`,
      ` */`,
      `import { defineEvent } from '@qmf/events';`,
      ``,
    ];
    for (const s of stubs) {
      body.push(
        `export const ${s.exportName} = defineEvent({`,
        `  name: '${s.name}',`,
        `  namespace: '${s.ns}',`,
        `  version: 1,`,
        `  description: 'Migrated from magic string; TODO: document.',`,
        `  payload: { type: 'object', additionalProperties: true },`,
        `  producers: [],`,
        `  consumers: [],`,
        `});`,
        ``,
      );
    }
    written = join(outDir, 'migrated.js');
    writeFileSync(written, body.join('\n'));
  }

  return { count: stubs.length, events: stubs, written };
}

/** @param {string} raw */
function normalizeEventName(raw) {
  if (raw.includes('.')) return raw;
  if (raw.includes(':')) {
    const [a, ...rest] = raw.split(':');
    return `${a}.${rest.join('.')}`;
  }
  return `app.${raw}`;
}

/** @param {string} name */
function toExportName(name) {
  return name
    .split(/[.:]/)
    .filter(Boolean)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
}
